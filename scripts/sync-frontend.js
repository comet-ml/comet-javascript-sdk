// Copies the browser bundle into a comet-react checkout, where JavaScript
// panels embed it in each panel's document:
//
//   npm run sync-frontend -- ../frontend
//
// Run `npm run pack` first (the npm script does). The copy starts with a
// comment naming the exact SDK build, from `git describe`.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const VENDOR_PATH =
  'src/experiment-management-shared/js-panels/vendor/comet-javascript-sdk.js';

const root = path.resolve(__dirname, '..');
const frontend = process.argv[2];

if (!frontend) {
  console.error('Usage: npm run sync-frontend -- <path to comet-react>');
  process.exit(1);
}

const target = path.resolve(frontend, VENDOR_PATH);

if (!fs.existsSync(path.dirname(path.dirname(target)))) {
  console.error(`${frontend} does not look like a comet-react checkout`);
  process.exit(1);
}

const version = execFileSync(
  'git',
  ['describe', '--tags', '--always', '--dirty'],
  { cwd: root, encoding: 'utf8' }
).trim();
const bundle = fs.readFileSync(
  path.join(root, 'build/comet-javascript-sdk.js'),
  'utf8'
);
const header =
  `/*! comet-javascript-sdk ${version}. Generated by \`npm run ` +
  'sync-frontend` in comet-ml/comet-javascript-sdk; do not edit. */\n';

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, header + bundle);

console.log(`Wrote comet-javascript-sdk ${version} to ${target}`);
if (version.endsWith('-dirty')) {
  console.warn('Warning: the SDK checkout has uncommitted changes.');
}
